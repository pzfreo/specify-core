//! Numbers formatted as specify-core's Python formats them, where the text reaches a person or a
//! JSON string, and the few Python text primitives the typed-spec readers stand on.
//!
//! Each function names the Python expression it reproduces. Python's float formatting is
//! correctly rounded (round half to even on the exact binary value) and so is Rust's, so the
//! digits come from Rust's formatter and only the layout (exponent form, signs, trailing zeros)
//! is Python's. `tests/pyfmt.rs` checks every function against Python's own output on a few
//! thousand values (`tests/fixtures/pyfmt.json`, generated by `tests/fixtures/pyfmt.py`).

/// Python's `f"{x:g}"`: six significant digits, trailing zeros dropped, exponent form (`1e+06`,
/// `1e-05`) below 1e-4 or from 1e6 on.
pub fn g(x: f64) -> String {
    general(x, 6)
}

/// Python's `f"{x:+g}"`: as [`g`], with a sign always (`+0`, `-0`, `+inf`).
pub fn signed_g(x: f64) -> String {
    let text = g(x);
    if text.starts_with('-') {
        text
    } else {
        format!("+{text}")
    }
}

/// Python's `f"{x:.{precision}f}"`: fixed point, `precision` decimals, `inf`, `-inf` and `nan`
/// as Python writes them.
pub fn fixed(x: f64, precision: usize) -> String {
    match special(x) {
        Some(text) => text.to_string(),
        None => format!("{x:.precision$}"),
    }
}

/// Python's `f"{x:.3f}".rstrip("0").rstrip(".")`: `choices._fmt` and `mates._fmt` (`6.6`, `8`,
/// `0.15`, `-0`).
pub fn fmt3(x: f64) -> String {
    let text = fixed(x, 3);
    if text.contains('.') {
        text.trim_end_matches('0').trim_end_matches('.').to_string()
    } else {
        text // inf, -inf, nan
    }
}

/// `rules._fmt`: [`g`] for a value close to a whole number (`math.isclose(x, round(x))`), else
/// [`fmt3`].
///
/// # Panics
///
/// On inf and nan, where Python raises (`round` cannot make them integers), with Python's
/// message: a dimension that is not finite is a bug upstream, not something to write.
pub fn fmt_rules(x: f64) -> String {
    if x.is_nan() {
        panic!("rules._fmt: cannot convert float NaN to integer");
    }
    if x.is_infinite() {
        panic!("rules._fmt: cannot convert float infinity to integer");
    }
    let whole = x.round_ties_even();
    // math.isclose with its default rel_tol=1e-9 and abs_tol=0.
    if (x - whole).abs() <= 1e-9 * x.abs().max(whole.abs()) {
        g(x)
    } else {
        fmt3(x)
    }
}

/// Python's `repr(x)` (and `str(x)`) of a float: the shortest text that reads back as `x`, in
/// fixed point from 1e-4 up to 1e16 (`5.0`, `0.0001`), otherwise in exponent form (`1e-05`,
/// `1e+16`); `inf`, `-inf`, `nan`.
pub fn repr(x: f64) -> String {
    if let Some(text) = special(x) {
        return text.to_string();
    }
    let (negative, digits, exp) = shortest_nearest(x);
    let sign = if negative { "-" } else { "" };
    if (-4..16).contains(&exp) {
        let body = if exp >= 0 {
            let point = exp as usize + 1;
            if digits.len() > point {
                format!("{}.{}", &digits[..point], &digits[point..])
            } else {
                format!("{digits}{}.0", "0".repeat(point - digits.len()))
            }
        } else {
            format!("0.{}{digits}", "0".repeat((-exp - 1) as usize))
        };
        format!("{sign}{body}")
    } else {
        format!("{sign}{}{}", mantissa(&digits), exponent(exp))
    }
}

/// Python's `round(x, digits)` on a float: the nearest multiple of `10**-digits`, ties to even,
/// judged on the exact binary value (so `round(2.675, 2)` is `2.67`: 2.675 is stored as
/// 2.67499999...). Python's limits are kept: more than 323 digits leaves `x` unchanged, fewer
/// than -308 gives a zero of `x`'s sign; inf, nan and zeros are returned unchanged.
///
/// # Panics
///
/// Where Python raises `OverflowError` (a negative `digits` rounding past f64's largest
/// value), with Python's message. No caller rounds to negative digits.
pub fn round_half_even(x: f64, digits: i32) -> f64 {
    if digits > 323 || x == 0.0 || !x.is_finite() {
        return x;
    }
    if digits < -308 {
        return 0.0 * x;
    }
    if digits >= 0 {
        // Rust's fixed formatting is the exact value correctly rounded, ties to even, as
        // Python's dtoa mode 3; reading it back is correctly rounded too.
        return format!("{x:.prec$}", prec = digits as usize)
            .parse()
            .expect("a formatted float reads back");
    }
    // Negative digits round the integer part: done on its exact decimal text.
    let places = (-digits) as usize;
    let text = format!("{:.0}", x.abs().trunc());
    let fraction_zero = x.fract() == 0.0;
    if text.len() < places {
        return 0.0 * x;
    }
    let (kept, dropped) = text.split_at(text.len() - places);
    let half = format!("5{}", "0".repeat(places - 1));
    let up = match dropped.cmp(half.as_str()) {
        std::cmp::Ordering::Greater => true,
        std::cmp::Ordering::Less => false,
        std::cmp::Ordering::Equal if !fraction_zero => true,
        std::cmp::Ordering::Equal => kept.bytes().last().is_some_and(|d| (d - b'0') % 2 == 1),
    };
    let mut kept = format!("0{kept}").into_bytes();
    if up {
        // Add one to the decimal text, carrying.
        for d in kept.iter_mut().rev() {
            if *d == b'9' {
                *d = b'0';
            } else {
                *d += 1;
                break;
            }
        }
    }
    let kept = String::from_utf8(kept).expect("ASCII digits");
    let rounded: f64 = format!("{kept}e{places}").parse().expect("a number");
    assert!(
        rounded.is_finite(),
        "round: rounded value too large to represent"
    );
    rounded.copysign(x)
}

/// Python's `float(text)` of a str: surrounding whitespace ignored, any Unicode decimal digit
/// read as its digit, underscores allowed between digits, `inf`, `infinity` and `nan` in any
/// case. `None` where Python raises `ValueError`.
pub fn parse_float(text: &str) -> Option<f64> {
    // As CPython: ASCII is kept; non-ASCII whitespace becomes a space, a decimal digit its
    // ASCII digit, any other character something no number contains. Then only ASCII
    // whitespace (space, \t, \n, \v, \f, \r) is stripped, so the ASCII separators U+001C to
    // U+001F, which `str.isspace` counts, are not.
    let ascii: String = text
        .chars()
        .map(|c| {
            if c.is_ascii() {
                c
            } else if is_space(c) {
                ' '
            } else if let Some(d) = decimal_digit(c) {
                char::from(b'0' + d)
            } else {
                '?'
            }
        })
        .collect();
    let trimmed = ascii.trim_matches(|c: char| c.is_ascii_whitespace() || c == '\x0b');
    if trimmed.is_empty() {
        return None;
    }
    let mut plain = String::with_capacity(trimmed.len());
    let mut prev = '\0';
    for c in trimmed.chars() {
        if c == '_' {
            if !prev.is_ascii_digit() {
                return None; // underscores only after digits
            }
        } else {
            if prev == '_' && !c.is_ascii_digit() {
                return None; // and only before digits
            }
            plain.push(c);
        }
        prev = c;
    }
    if prev == '_' {
        return None;
    }
    // Rust reads the same grammar (sign, digits with an optional point and exponent, inf,
    // infinity, nan in any case), and nothing else: no hex, no inner spaces.
    plain.parse().ok()
}

/// Python's `int(text)` of a str of decimal digits (what a regex `\d+` matched): any Unicode
/// decimal digit read as its digit. `None` if a character is not a decimal digit or the value
/// does not fit a `u64`.
pub fn parse_digits(text: &str) -> Option<u64> {
    if text.is_empty() {
        return None;
    }
    text.chars().try_fold(0u64, |acc, c| {
        acc.checked_mul(10)?
            .checked_add(u64::from(decimal_digit(c)?))
    })
}

/// Python's `str.isspace` for one character: Unicode White_Space and the four ASCII
/// information separators (0x1C to 0x1F), which Python counts as whitespace (their bidirectional
/// class is B or S). It is what `str.split()` and `str.strip()` split and strip on, and what
/// `re`'s `\s` matches.
pub fn is_space(c: char) -> bool {
    c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c)
}

/// Python's `" ".join(text.split())`: runs of whitespace as one space, none at either end.
pub fn squash_spaces(text: &str) -> String {
    text.split(is_space)
        .filter(|w| !w.is_empty())
        .collect::<Vec<_>>()
        .join(" ")
}

/// Python's `text.strip()`.
pub fn strip(text: &str) -> &str {
    text.trim_matches(is_space)
}

/// Python's `repr(text)` of a str: single quotes unless the text holds a single quote and no
/// double quote; backslash, the quote, tab, newline and return escaped; other control and
/// non-printable characters as `\xhh`, `\uhhhh` or `\Uhhhhhhhh`.
pub fn repr_str(text: &str) -> String {
    let quote = if text.contains('\'') && !text.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::with_capacity(text.len() + 2);
    out.push(quote);
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\t' => out.push_str("\\t"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            c if c < ' ' || c == '\x7f' => out.push_str(&format!("\\x{:02x}", c as u32)),
            c if c.is_ascii() || is_printable(c) => out.push(c),
            c if (c as u32) < 0x100 => out.push_str(&format!("\\x{:02x}", c as u32)),
            c if (c as u32) < 0x10000 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push_str(&format!("\\U{:08x}", c as u32)),
        }
    }
    out.push(quote);
    out
}

/// Python's `str.isprintable` for one character: not in the categories Other (Cc, Cf, Cs, Co,
/// Cn) or Separator (Zl, Zp, Zs), except the ASCII space.
pub fn is_printable(c: char) -> bool {
    use std::sync::LazyLock;
    static NOT_PRINTABLE: LazyLock<regex::Regex> =
        LazyLock::new(|| regex::Regex::new(r"^[\p{C}\p{Z}]$").expect("valid pattern"));
    c == ' ' || !NOT_PRINTABLE.is_match(c.encode_utf8(&mut [0; 4]))
}

/// The value of a Unicode decimal digit (category Nd), as Python's `unicodedata.decimal`.
pub fn decimal_digit(c: char) -> Option<u8> {
    let code = c as u32;
    if c.is_ascii_digit() {
        return Some(code as u8 - b'0');
    }
    // Every Unicode decimal digit is in a run of ten from its zero.
    let zero = match DECIMAL_ZEROS.binary_search(&code) {
        Ok(i) => DECIMAL_ZEROS[i],
        Err(0) => return None,
        Err(i) => DECIMAL_ZEROS[i - 1],
    };
    (code - zero < 10).then(|| (code - zero) as u8)
}

/// The zero of every run of Unicode decimal digits, from Python 3.14's `unicodedata` (Unicode
